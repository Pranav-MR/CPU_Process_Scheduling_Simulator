import http.server
import json
import os
import subprocess
import sys
import webbrowser

PORT = 5000
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
FRONTEND_DIR = os.path.join(BASE_DIR, "frontend")
BACKEND_DIR = os.path.join(BASE_DIR, "c_backend")
EXECUTABLE_NAME = "scheduler.exe" if sys.platform == "win32" else "scheduler"
EXECUTABLE_PATH = os.path.join(BACKEND_DIR, EXECUTABLE_NAME)
C_SOURCE_PATH = os.path.join(BACKEND_DIR, "scheduler.c")


def ensure_backend_compiled():
    """Ensure the C scheduler is compiled before handling requests."""
    if not os.path.exists(EXECUTABLE_PATH) or (
        os.path.exists(C_SOURCE_PATH)
        and os.path.getmtime(C_SOURCE_PATH) > os.path.getmtime(EXECUTABLE_PATH)
    ):
        print("[Server] Compiling C backend with gcc...")
        compile_cmd = ["gcc", "-Wall", "-O2", C_SOURCE_PATH, "-o", EXECUTABLE_PATH]
        result = subprocess.run(compile_cmd, capture_output=True, text=True)
        if result.returncode != 0:
            print("[Server] Compilation Error:\n", result.stderr)
            raise RuntimeError(f"C Compilation Failed: {result.stderr}")
        print("[Server] Compilation successful!")


class SchedulingRequestHandler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=FRONTEND_DIR, **kwargs)

    def do_POST(self):
        if self.path == "/api/simulate":
            try:
                content_length = int(self.headers.get("Content-Length", 0))
                post_body = self.rfile.read(content_length).decode("utf-8")
                data = json.loads(post_body)

                algorithm = data.get("algorithm", "FCFS").strip()
                quantum = int(data.get("quantum", 2))
                processes = data.get("processes", [])

                if not processes:
                    self.send_error_response("No processes provided.")
                    return

                # Ensure backend is compiled
                ensure_backend_compiled()

                # Build stdin payload for C executable:
                # Format: <ALGO> <QUANTUM> <N>\n<ID> <ARRIVAL> <BURST>\n...
                stdin_lines = [f"{algorithm} {quantum} {len(processes)}"]
                for p in processes:
                    pid = str(p.get("id", "")).strip().replace(" ", "_")
                    arrival = int(p.get("arrival", 0))
                    burst = int(p.get("burst", 1))
                    stdin_lines.append(f"{pid} {arrival} {burst}")

                stdin_text = "\n".join(stdin_lines) + "\n"

                # Invoke compiled C backend
                proc = subprocess.run(
                    [EXECUTABLE_PATH],
                    input=stdin_text,
                    text=True,
                    capture_output=True,
                    timeout=5
                )

                if proc.returncode != 0:
                    err_msg = proc.stderr.strip() or "C Scheduler exited with error."
                    self.send_error_response(err_msg, status=500)
                    return

                # Send back the JSON generated by C
                response_bytes = proc.stdout.encode("utf-8")
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(response_bytes)))
                self.send_header("Access-Control-Allow-Origin", "*")
                self.end_headers()
                self.wfile.write(response_bytes)

            except Exception as e:
                self.send_error_response(f"Internal server error: {str(e)}", status=500)
        else:
            self.send_error(404, "Endpoint not found")

    def send_error_response(self, message, status=400):
        error_json = json.dumps({"error": message}).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(error_json)))
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()
        self.wfile.write(error_json)

    def do_OPTIONS(self):
        # Support CORS pre-flight if needed
        self.send_response(200)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()


def run_server():
    ensure_backend_compiled()
    server_address = ("", PORT)
    httpd = http.server.HTTPServer(server_address, SchedulingRequestHandler)
    print("=" * 60)
    print("  CPU Process Scheduling Simulator - C Data Structures")
    print("=" * 60)
    print(f"Server running at: http://localhost:{PORT}")
    print(f"Frontend directory: {FRONTEND_DIR}")
    print(f"C Backend binary:   {EXECUTABLE_PATH}")
    print("Press Ctrl+C to stop the server.")
    print("=" * 60)
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nServer stopped.")


if __name__ == "__main__":
    run_server()
